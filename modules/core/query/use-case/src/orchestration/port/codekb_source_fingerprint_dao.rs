//! `CodekbSourceFingerprintDao` ポート — 作業ツリーの内容指紋を引く DAO。

/// 与えたパスに限った**作業ツリーの内容指紋**を引く（**読取専用**）。
///
/// 「今ディスクに在るもの」を内容アドレスで表した値であり、コミット済みかどうかに依らない。
/// これがあるから、リベースや squash で歴史が書き換わってもストアの鮮度判定は壊れず、編集を
/// 元に戻せば指紋も元に戻る。
///
/// どのリポジトリを見るか、どのパスを除くか（単一リポジトリ構成では枠組み自身の `aidlc/` を
/// 除く）は**実装が握る** — 合成ルートが結線するので、ポート面には現れない。
///
/// # 失敗の通路を持たない
///
/// 戻り値が `Result` ではなく [`Option`] なのは、upstream が「git 作業ツリーではない・git が
/// 無い・pathspec が不正／不一致・1 つも stage されない」を**すべて同じ `null`** に畳んで
/// いるからである（呼び手はそれを `UNVERIFIED` や `unknown` として判定に載せ、決して偽の
/// 判定や空ツリーの指紋を返さない）。ここに失敗の通路を足すと、upstream が観測させない差が
/// 生まれる。
pub trait CodekbSourceFingerprintDao {
    /// 与えたパスに限った内容指紋を引く（計算できなければ `None`）。
    fn find(&self, paths: &[String]) -> Option<String>;
}
