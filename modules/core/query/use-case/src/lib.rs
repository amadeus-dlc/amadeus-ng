//! **クエリ側**のユースケース層 — 構造化リードモデルを鍵で引く口と、そのクエリモデル。
//!
//! クエリ側は RMU が構築したリードモデル (SQLite の `read_*` 表) だけに依存し、それを
//! **自前のビュー型**へ写して読む。ドメイン (`core-command-domain`) には絶対依存せず、
//! 集約の再構成もしない (`coding-rules/cqrs-boundaries.md` 規則 6 / 2026-08-29 オーナー
//! 裁定)。`Cargo.toml` にコマンド側クレートが**無いこと**がその機械強制であり、違反は
//! ビルドで落ちる。
//!
//! 型はコマンド側ドメインの写しではなく**側ごとの専用モデル**である (同規則「共有部品は
//! 側の独立を DRY に優先」)。両側が同じ Published Language を読むので形は似るが、
//! 変更理由は独立している — コマンド側の集約が変わってもこちらは動かない。
//!
//! # 読むことしか許されない
//!
//! ユースケースの本体は `execute(鍵) = dao.find(鍵) → View` である。判断・導出・選択・
//! 文言組立はどれも持たない (オーナー裁定 2026-09-02) — 答えは RMU が集約のクエリを呼んで
//! 行に焼いてあり、どう描くかは出す側 (合成ルートのプレゼンタ) が行の綴りに従って決める。
//! 複数の表にまたがる答えは**FK をたどって表ごとに引く**ことで組む (同 2026-09-03)。
//!
//! # モジュールの分担
//!
//! コンテキストは [`orchestration`] 1 つで、その中が責務ごとに分かれる。
//!
//! - `orchestration/port/` — リードモデルを読む **DTO/DAO ポート**。DAO の契約 (trait) と
//!   ポート面のエラーに加え、**DAO が依存する DTO (行の写し) も同居する** — DTO/DAO ポートは
//!   一つのパッケージである (オーナー裁定 2026-08-31)。**1 表 1 ポート 1 View**。
//! - `orchestration` 直下 — 鍵で引くユースケース、複数の表にまたがる組み立て View、そして
//!   読み手が放出する directive プロトコル (公開言語 B14)。
//!
//! `port` の mod は private であり、公開 API は [`orchestration`] のフラットなファサード
//! (`pub use`) が唯一の宣言である。消費側のパスは読む対象によらず
//! `core_query_use_case::orchestration::<型>` で安定する
//! (`coding-rules/module-visibility.md`)。

