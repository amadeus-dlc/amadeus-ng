//! **クエリ側の全実体** — ReadModelUpdater（U4）。
//!
//! amadeus-ng のクエリ側は「リードモデル（`aidlc-state.md` と監査シャード）を書く」側であり、
//! 読取 API のユースケース層はまだ存在しない。したがってクエリ側はこのクレート 1 つで完結する
//! （2026-08-29 オーナー裁定 / ADR-009）。
//!
//! # 二層構造（2026-08-28 裁定）
//!
//! RMU は 2 つの層でできている。
//!
//! 1. **取得ループ** [`orchestration::ReadModelUpdater`] — チェックポイントを読み、
//!    `events_after` で差分を引き、投影核へ渡し、`advance_checkpoint` で前進する。
//!    ストレージ・接続・チェックポイントを知るのはこちらだけである。
//! 2. **純粋投影核** [`workspace::project`] — ドメインイベントの列とリードモデルだけを
//!    受け取り、リードモデルを作成・更新する。`JournalReader`・SQLite 接続・チェックポイントを
//!    **一切知らない**。
//!
//! 二層を潰してはならない（`coding-rules/cqrs-boundaries.md` 禁止パターン）。投影核が取得の
//! 都合を知ると、投影の規則だけを単体でテストできなくなる。
//!
//! # なぜコマンド側クレートが `Cargo.toml` に無いのか
//!
//! RMU は「橋」だが、橋であることと両側を広く使ってよいことは別である。投影核の入口は
//! ドメインイベント 1 本に絞ってあり、コマンド側の型（集約・Repository・ストアのエラー）は
//! 入口に現れない。したがって依存は共有層（`core-domain`）と自前のストレージ結合
//! （rusqlite）だけで足り、コマンド側クレートは 1 つも要らない。境界はクレート分離で物理
//! 強制する — 違反はビルドで落ちる。

